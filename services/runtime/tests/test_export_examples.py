@pytest.mark.parametrize("format", ["ink", "yarn_spinner"])
def test_empty_project_has_no_invented_executable_entry(format):
    document = document_for(load_project_fixture(PROJECTS / "citadel-branch.v1.json"))
    projection = ExportProjectionService().build(document, ExportOptionsV1(
        format=format, scope="whole_project", engine_tag_target=format,
    )).projection
    executable = ExecutableProjectionService().build(projection)
    adapter = InkExportService(compiler_policy="disabled") if format == "ink" else YarnSpinnerExportService(compiler_policy="disabled")
    result = adapter.build(executable)
    assert result.payload is None
    assert any(item.code.endswith("missing-entry") for item in result.diagnostics)


@pytest.mark.parametrize("format", ["json", "yaml", "ink", "yarn_spinner"])
def test_every_format_preserves_russian_authored_text_without_changing_input(format):
    payload = ready_aurora().model_dump(mode="json")
    node = next(item for item in payload["nodes"] if item["id"] == "node-opening")
    node["body"] = "Проверка груза начинается.\nМара ждёт ответа."
    document = document_for(type(ready_aurora()).model_validate(payload))
    before = deepcopy(document.model_dump(mode="json"))
    output = render_example(document, ExportOptionsV1(
        format=format, scope="story_flows", story_flow_ids=["flow-main-story"],
        engine_tag_target=format if format in {"ink", "yarn_spinner"} else "generic",
    ))
    assert "Проверка груза начинается." in output.decode()
    assert "Мара ждёт ответа." in output.decode()
    assert document.model_dump(mode="json") == before


def test_reviewed_example_imports_and_reopens_without_tag_synthesis_or_lock(tmp_path):
    destination = tmp_path / "AuroraExport.narrative"
    imported = import_project_fixture(PROJECTS / READY_NAME, destination)
    registry = ProjectSessionRegistry()
    opened = registry.open(destination)
    try:
        assert opened.document.checksum == imported.document.checksum
        assert opened.document.engine_tag_definitions == imported.document.engine_tag_definitions
    finally:
        registry.close(opened.session.session_id)
    assert not (destination / "cache/project.lock.json").exists()
