EntityT = TypeVar("EntityT")


@runtime_checkable
class BatchAddRepository(Protocol[EntityT]):
    """Optional atomic-group insertion; the calling UoW still owns commit.

    Typed Node JSON references may use local Nodes in the same atomic group.
    Other references retain fresh checks. Adapters without a safe batching
    implementation preserve dependency input order through ordinary adds.
    """

    def add_many(self, entities: Sequence[EntityT]) -> Sequence[EntityT]: ...


