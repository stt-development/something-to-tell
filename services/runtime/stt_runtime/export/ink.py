"""Readable Ink source adapter with Playback-owned ordering and exact source maps."""

from dataclasses import dataclass, field
import json
import math
import re
import struct

from ..schemas.executable_export import (
    ExecutableConditionBinaryV1, ExecutableConditionLiteralV1,
    ExecutableConditionStateV1,
)
from ..schemas.export import EXPORT_MAX_OUTPUT_BYTES, ExportDiagnosticV1, ExportOwnerV1
from .ink_compiler import (
    INK_VERSION, InkCompiler, InkCompilerPolicy, InkCompilerValidation, OfficialInkCompiler,
)
from .ink_state import (
    condition, condition_nodes, initial_values, literal, once_variable,
    owned_conditions, state_variables, variable,
)


@dataclass(frozen=True, slots=True)
class InkSourceMapLine:
    symbol: str
    start_line: int
    end_line: int
    owner: ExportOwnerV1


@dataclass(frozen=True, slots=True)
class InkSourceBuild:
    payload: bytes | None
    source_map: tuple[InkSourceMapLine, ...]
    diagnostics: tuple[ExportDiagnosticV1, ...]
    compiler: InkCompilerValidation


@dataclass(slots=True)
class _Writer:
    """Keep line-level provenance while rendering one atomic source artifact."""

    owners: dict[str, ExportOwnerV1]
    lines: list[str] = field(default_factory=list)
    mappings: list[InkSourceMapLine] = field(default_factory=list)

    def mapped(self, symbol: str, lines: list[str]) -> None:
        start = len(self.lines) + 1
        self.lines.extend(lines)
        if symbol in self.owners and lines:
            self.mappings.append(InkSourceMapLine(
                symbol, start, len(self.lines), self.owners[symbol]
            ))

    def knot(self, symbol: str) -> None:
        self.mapped(symbol, ["", f"=== {symbol} ==="])


class InkExportService:
    """Render the executable contract without acquiring storage or authoring state."""

    media_type = "text/x-ink"
    extension = ".ink"

    def __init__(self, compiler: InkCompiler | None = None, *,
                 compiler_policy: InkCompilerPolicy = "optional") -> None:
        if compiler_policy not in {"disabled", "optional", "required"}:
            raise ValueError("invalid Ink compiler policy")
        self._compiler = compiler or OfficialInkCompiler()
        self._policy = compiler_policy

    def build(self, executable) -> InkSourceBuild:
        owners = {item.symbol: item.owner for item in executable.source_map}
        diagnostics = [*executable.diagnostics, *self._validate(executable, owners)]
        if any(item.severity == "error" for item in diagnostics):
            return InkSourceBuild(None, (), tuple(diagnostics), InkCompilerValidation("disabled"))
        writer = _Writer(owners)
        operations = {item.id: item for item in executable.operations}
        variables = state_variables(executable)
        for operation in executable.operations:
            if operation.effect.operation == "record_dialogue_choice":
                payload = operation.effect.payload
                variables[variable(["dialogue", payload.dialogue_node_id, payload.choice_id])] = False
        writer.lines.extend([
            "// Generated by Something To Tell Engine from ExecutableNarrativeProjectionV1.",
            f"// stt-ink-target: ink/inklecate {INK_VERSION}",
            f"// stt-source-checksum: {executable.source.source_checksum}",
        ])
        roots = [flow for flow in executable.flows if flow.is_root]
        for flow in roots:
            writer.mapped(flow.symbol, [f"// stt-entry: entry_{flow.symbol}"])
        writer.lines.extend(f"VAR {key} = {literal(value)}" for key, value in sorted(variables.items()))
        if executable.host_bindings:
            writer.lines.append("EXTERNAL stt_transfer_item(item, from_kind, from_id, to_kind, to_id)")
        if len(roots) == 1:
            writer.lines.append(f"-> entry_{roots[0].symbol}")
        else:
            for flow in roots:
                writer.lines.append(f"+ [{self._escape(flow.name)}] -> entry_{flow.symbol}")
        states = {state.flow_id: state for state in executable.initial_states}
        returns = {item.source_step_symbol: item for flow in executable.flows for item in flow.returns}
        for flow in executable.flows:
            if flow.is_root:
                writer.owners[f"entry_{flow.symbol}"] = owners[flow.symbol]
                writer.knot(f"entry_{flow.symbol}")
                for key, value in sorted(initial_values(states[flow.id]).items()) if flow.id in states else []:
                    writer.lines.append(f"~ {key} = {literal(value)}")
                writer.lines.extend([f"-> {flow.symbol} ->", "-> END"])
            writer.knot(flow.symbol)
            writer.lines.append(f"-> {flow.entry_step_symbol}")
            for step in flow.steps:
                writer.knot(step.symbol)
                writer.mapped(step.symbol, self._text(step.text))
                writer.lines.append(f"~ {variable(['visited', step.node_id])} = true")
                self._effects(writer, step.operation_ids, operations)
                if step.symbol in returns:
                    exit_record = returns[step.symbol]
                    self._effects(writer, exit_record.operation_ids, operations)
                    writer.mapped(exit_record.symbol, [
                        f"~ stt_return_key = {literal(exit_record.symbol)}", "->->"
                    ])
                    continue
                if step.dialogue_symbol:
                    writer.lines.extend([
                        '~ stt_dialogue_outcome = ""', '~ stt_dialogue_option = ""',
                        f"-> {step.dialogue_symbol} ->",
                    ])
                self._routes(writer, step.routes, operations)
        self._dialogues(writer, executable, operations)
        self._quests(writer, executable, operations)
        if executable.host_bindings:
            writer.lines.append('// stt-host-function: ' + json.dumps({
                "name": "stt_transfer_item", "version": 1, "returns": "boolean",
                "parameters": ["item", "from_kind", "from_id", "to_kind", "to_id"],
                "lookahead_safe": False,
            }, sort_keys=True))
        for entry in writer.mappings:
            writer.lines.append('// stt-source-map: ' + json.dumps({
                "symbol": entry.symbol, "start_line": entry.start_line,
                "end_line": entry.end_line, "owner": entry.owner.model_dump(mode="json"),
            }, ensure_ascii=False, sort_keys=True))
        payload = ("\n".join(writer.lines) + "\n").encode("utf-8")
        if len(payload) > EXPORT_MAX_OUTPUT_BYTES:
            diagnostics.append(self._diagnostic("limit-exceeded", None, {"bytes": len(payload)}))
            return InkSourceBuild(None, tuple(writer.mappings), tuple(diagnostics), InkCompilerValidation("disabled"))
        validation = InkCompilerValidation("disabled") if self._policy == "disabled" else self._compiler.validate(payload)
        if validation.status not in {"valid", "disabled"}:
            optional = self._policy == "optional" and validation.status == "unavailable"
            diagnostics.append(self._diagnostic(
                f"compiler-{validation.status}", None,
                {"compiler": f"inklecate {INK_VERSION}", "detail": validation.detail},
                severity="warning" if optional else "error",
            ))
        return InkSourceBuild(
            None if any(item.severity == "error" for item in diagnostics) else payload,
            tuple(writer.mappings), tuple(diagnostics), validation,
        )

    def _routes(self, writer, routes, operations) -> None:
        if not routes:
            writer.lines.append('~ stt_return_key = ""')
            writer.lines.append("->->")
            return
        owned = any(route.dialogue_element_id for route in routes if route.kind == "jump")
        availability = {}
        origins = {}
        for route in routes:
            eligible = condition(route.condition)
            origin_filter = "true"
            if owned and route.kind == "jump":
                if route.dialogue_element_id:
                    origin = literal(route.dialogue_element_id)
                    origin_filter = f"(stt_dialogue_outcome == {origin} or stt_dialogue_option == {origin})"
                else:
                    origin_filter = "false"
            origins[route.id] = origin_filter
            availability[route.id] = f"({origin_filter} and {eligible})"
        non_default = [availability[item.id] for item in routes if not item.is_default]
        fallback = f"not ({' or '.join(non_default)})" if non_default else "true"
        for route in routes:
            eligible = f"({origins[route.id]} and {fallback})" if route.is_default else availability[route.id]
            # Sticky, choice-only text preserves repeat visits and avoids echoing labels.
            writer.mapped(route.symbol, [f"+ {{ {eligible} }} [{self._escape(route.label or route.id)}]"])
            self._effects(writer, route.operation_ids, operations, indent="    ")
            if route.kind == "jump":
                writer.mapped(route.symbol, [f"    -> {route.target_symbol}"])
            else:
                writer.mapped(route.symbol, [f"    -> {route.target_symbol} ->"])
                for binding in route.return_bindings:
                    writer.mapped(route.symbol, [
                        f"    {{ stt_return_key == {literal(binding.exit_symbol)}:",
                        f"        -> {binding.target_step_symbol}", "    }",
                    ])
                # A missing return is a blocked path, never an invented continuation.
                writer.lines.extend(["    # stt-blocked: unbound-flow-return", "    -> END"])

    def _dialogues(self, writer, executable, operations) -> None:
        speakers = {item.symbol: item.display_name for item in executable.speakers}
        for dialogue in executable.dialogues:
            writer.knot(dialogue.symbol)
            writer.lines.append(f"-> {dialogue.entry_symbol}" if dialogue.entry_symbol else "->->")
            for line in dialogue.lines:
                writer.knot(line.symbol)
                prefix = speakers.get(line.speaker_symbol, "")
                writer.mapped(line.symbol, self._text(line.text, prefix=f"{prefix}: " if prefix else ""))
                self._effects(writer, line.operation_ids, operations)
                writer.mapped(line.symbol, [f"~ stt_dialogue_outcome = {literal(line.id)}"])
                writer.lines.append(f"-> {line.next_symbol}" if line.next_symbol else "->->")
            for choice in dialogue.choices:
                writer.knot(choice.symbol)
                writer.mapped(choice.symbol, self._text(choice.prompt))
                self._effects(writer, choice.operation_ids, operations)
                for option in choice.options:
                    writer.mapped(option.symbol, [
                        f"+ {{ {condition(option.condition)} }} [{self._escape(option.text)}]",
                        f"    ~ stt_dialogue_option = {literal(option.id)}",
                        f"    ~ stt_dialogue_outcome = {literal(option.id)}",
                    ])
                    self._effects(writer, option.operation_ids, operations, indent="    ")
                    writer.lines.append(f"    -> {option.next_symbol}" if option.next_symbol else "    ->->")
                if not choice.options:
                    writer.lines.extend(["# stt-blocked: empty-dialogue-choice", "-> END"])

    def _quests(self, writer, executable, operations) -> None:
        # Quest stages are explicit host-callable tunnels; Flow playback continues
        # through its authored transitions without inventing an extra Quest menu.
        for quest in executable.quests:
            writer.knot(quest.symbol)
            writer.mapped(quest.symbol, self._text(quest.objective))
            writer.lines.append(f"-> {quest.entry_stage_symbol}" if quest.entry_stage_symbol else "->->")
            for stage in quest.stages:
                writer.knot(stage.symbol)
                writer.mapped(stage.symbol, self._text(stage.description or stage.title))
                for branch in stage.branches:
                    writer.mapped(branch.symbol, [
                        f"+ {{ {condition(branch.condition)} }} [{self._escape(branch.label)}]"
                    ])
                    self._effects(writer, branch.operation_ids, operations, indent="    ")
                    writer.lines.append(f"    -> {branch.target_stage_symbol}" if branch.target_stage_symbol else "    ->->")
                if not stage.branches:
                    writer.lines.append("->->")

    def _effects(self, writer, identifiers, operations, *, indent="") -> None:
        for identifier in identifiers:
            operation = operations[identifier]
            effect = operation.effect
            payload = effect.payload
            lines = []
            if effect.operation in {"set_flag", "clear_flag"}:
                lines.append(f"~ {variable(['flags', payload.flag])} = {'true' if effect.operation == 'set_flag' else 'false'}")
            elif effect.operation == "set_quest_status":
                lines.append(f"~ {variable(['quests', payload.quest_node_id, 'status'])} = {literal(payload.status)}")
            elif effect.operation == "record_dialogue_choice":
                lines.append(f"~ {variable(['dialogue', payload.dialogue_node_id, payload.choice_id])} = true")
            elif effect.operation == "transfer_item":
                root = ["items", payload.item_node_id, "holder"]
                args = ', '.join(literal(value) for value in [
                    payload.item_node_id, payload.from_holder.kind, payload.from_holder.node_id or "",
                    payload.to_holder.kind, payload.to_holder.node_id or "",
                ])
                expected = (
                    f"{variable([*root, 'kind'])} == {literal(payload.from_holder.kind)} and "
                    f"{variable([*root, 'node_id'])} == {literal(payload.from_holder.node_id or '')}"
                )
                lines.extend([
                    f"{{ not ({expected}):", "    # stt-blocked: custody-precondition", "    -> END", "}",
                    f"{{ not stt_transfer_item({args}):", "    # stt-blocked: host-transfer-failed", "    -> END", "}",
                    f"~ {variable([*root, 'kind'])} = {literal(payload.to_holder.kind)}",
                    f"~ {variable([*root, 'node_id'])} = {literal(payload.to_holder.node_id or '')}",
                    f"~ {variable(['inventory', payload.item_node_id])} = {literal(payload.to_holder.kind in {'player', 'party'})}",
                ])
            if effect.repeat_policy == "once":
                guard = once_variable(effect.id)
                lines = [f"{{ not {guard}:", *[f"    {line}" for line in lines], f"    ~ {guard} = true", "}"]
            writer.mapped(operation.symbol, [indent + line for line in lines])

    @staticmethod
    def _escape(value: str) -> str:
        # Escape Ink tokens so authored prose cannot become a divert, tag, choice,
        # comment, glue, or expression. Normal prose stays readable and bilingual.
        result = re.sub(r"([\\{}\[\]#*+~|<>=\-/])", r"\\\1", value)
        # Ink also recognizes declaration/include keywords without punctuation.
        result = re.sub(r"^(\s*)(VAR|CONST|LIST|INCLUDE|EXTERNAL|TODO)(?=\b)",
                        lambda match: match[1] + "\\" + match[2], result)
        return result.replace("\r", " ").replace("\n", " ")

    def _text(self, value: str, *, prefix="") -> list[str]:
        return [self._escape(prefix + line) for line in value.replace("\r\n", "\n").split("\n") if line]

    def _validate(self, executable, owners) -> list[ExportDiagnosticV1]:
        diagnostics = []
        def reject(code, symbol=None, **parameters):
            diagnostics.append(self._diagnostic(code, owners.get(symbol), parameters))
        if not any(flow.is_root for flow in executable.flows):
            reject("missing-entry", reason="select a Story Flow with a valid entry")
        symbols = [item.symbol for item in executable.source_map]
        if len(symbols) != len(set(symbols)):
            reject("identifier-collision")
        roots = [flow for flow in executable.flows if flow.is_root]
        initial = {state.flow_id: state for state in executable.initial_states}
        for symbol, expression in owned_conditions(executable):
            for node in condition_nodes(expression):
                if isinstance(node, ExecutableConditionBinaryV1) and node.operator in {"in", "not_in"}:
                    reject("unsupported-condition", symbol, operator=node.operator)
                if isinstance(node, ExecutableConditionBinaryV1) and node.operator in {"lt", "lte", "gt", "gte"}:
                    if any(isinstance(operand, ExecutableConditionStateV1) or (
                        isinstance(operand, ExecutableConditionLiteralV1) and operand.value_type != "number"
                    ) for operand in [node.left, node.right]):
                        reject("unsupported-condition", symbol, reason="Ink cannot preserve ordered string comparison")
                if isinstance(node, ExecutableConditionLiteralV1):
                    if node.value is None:
                        reject("unsupported-null", symbol, reason="use an explicit holder kind comparison")
                    elif isinstance(node.value, (float, int)) and not isinstance(node.value, bool):
                        if not math.isfinite(node.value) or abs(node.value) > 2**24 or (
                            isinstance(node.value, float) and struct.unpack("f", struct.pack("f", node.value))[0] != node.value
                        ):
                            reject("unsupported-number", symbol, reason="outside exact supported numeric range")
                    elif isinstance(node.value, str) and any(char in node.value for char in '\n\r{}'):
                        reject("unsupported-string-literal", symbol, reason="Ink interpolates braces in expression strings")
                if isinstance(node, ExecutableConditionStateV1) and node.path[0] == "dialogue":
                    reject("unsupported-condition", symbol, reason="Dialogue choice history is a collection")
                if isinstance(node, ExecutableConditionStateV1) and node.path[0] in {"items", "quests"}:
                    for root in roots:
                        state = initial.get(root.id)
                        known = state is not None and (
                            node.path[1] in state.quest_statuses if node.path[0] == "quests"
                            else any(item.item_node_id == node.path[1] for item in state.item_custody)
                        )
                        if not known:
                            reject("unsupported-condition", symbol,
                                   reason="initialize Item custody or Quest status for every selected root",
                                   flow_id=root.id, state_path=".".join(node.path))
                if isinstance(node, ExecutableConditionBinaryV1) and node.operator in {"eq", "ne"}:
                    operands = [node.left, node.right]
                    if any(isinstance(operand, ExecutableConditionStateV1) and (
                        operand.path[0] == "items" and operand.path[-1] == "node_id"
                    ) for operand in operands) and any(
                        isinstance(operand, ExecutableConditionLiteralV1) and operand.value == ""
                        for operand in operands
                    ):
                        reject("unsupported-null", symbol,
                               reason="nullable holder node ids cannot be compared to an empty string")
        operations = {item.id: item for item in executable.operations}
        flows = {item.symbol: item for item in executable.flows}
        host_ids = {item.id for item in executable.host_bindings if item.operation == "transfer_item"}
        defined = {flow.symbol for flow in executable.flows}
        defined.update(step.symbol for flow in executable.flows for step in flow.steps)
        defined.update(item.symbol for item in executable.dialogues)
        defined.update(line.symbol for item in executable.dialogues for line in item.lines)
        defined.update(choice.symbol for item in executable.dialogues for choice in item.choices)
        defined.update(item.symbol for item in executable.quests)
        defined.update(stage.symbol for item in executable.quests for stage in item.stages)
        knot_symbols = [
            *(flow.symbol for flow in executable.flows),
            *(f"entry_{flow.symbol}" for flow in executable.flows if flow.is_root),
            *(step.symbol for flow in executable.flows for step in flow.steps),
            *(item.symbol for item in executable.dialogues),
            *(line.symbol for item in executable.dialogues for line in item.lines),
            *(choice.symbol for item in executable.dialogues for choice in item.choices),
            *(item.symbol for item in executable.quests),
            *(stage.symbol for item in executable.quests for stage in item.stages),
        ]
        if len(knot_symbols) != len({symbol.casefold() for symbol in knot_symbols}):
            reject("identifier-collision", reason="duplicate generated knot names")
        references = []
        bindings = []
        call_graph = {flow.symbol: [] for flow in executable.flows}
        for flow in executable.flows:
            references.append((flow.symbol, flow.entry_step_symbol))
            for step in flow.steps:
                bindings.append((step.symbol, step.operation_ids))
                if step.dialogue_symbol:
                    references.append((step.symbol, step.dialogue_symbol))
                for route in step.routes:
                    references.append((route.symbol, route.target_symbol))
                    references.extend((route.symbol, item.target_step_symbol) for item in route.return_bindings)
                    bindings.append((route.symbol, route.operation_ids))
                    if route.kind == "call":
                        call_graph[flow.symbol].append(route.target_symbol)
                        if not route.return_bindings:
                            reject("unbound-return", route.symbol, reason="add a named exit return binding")
                        called = flows.get(route.target_symbol)
                        if called:
                            expected = {item.symbol for item in called.returns}
                            bound = {item.exit_symbol for item in route.return_bindings}
                            if expected != bound:
                                reject("unbound-return", route.symbol,
                                       reason="return maps must match the called Flow's named exits")
            source_steps = [item.source_step_symbol for item in flow.returns]
            if len(source_steps) != len(set(source_steps)):
                reject("ambiguous-exit", flow.symbol, reason="multiple exits on the same step")
            for item in flow.returns:
                references.append((item.symbol, item.source_step_symbol))
                bindings.append((item.symbol, item.operation_ids))
        for dialogue in executable.dialogues:
            if dialogue.entry_symbol:
                references.append((dialogue.symbol, dialogue.entry_symbol))
            else:
                reject("missing-entry", dialogue.symbol, reason="Dialogue entry is missing")
            for line in dialogue.lines:
                bindings.append((line.symbol, line.operation_ids))
                if line.next_symbol:
                    references.append((line.symbol, line.next_symbol))
            for choice in dialogue.choices:
                bindings.append((choice.symbol, choice.operation_ids))
                for option in choice.options:
                    bindings.append((option.symbol, option.operation_ids))
                    if option.next_symbol:
                        references.append((option.symbol, option.next_symbol))
        for quest in executable.quests:
            if quest.entry_stage_symbol:
                references.append((quest.symbol, quest.entry_stage_symbol))
            elif quest.stages:
                reject("missing-entry", quest.symbol, reason="Quest stage entry is missing")
            for stage in quest.stages:
                for branch in stage.branches:
                    bindings.append((branch.symbol, branch.operation_ids))
                    if branch.target_stage_symbol:
                        references.append((branch.symbol, branch.target_stage_symbol))
        for symbol, target in references:
            if target not in defined:
                reject("missing-reference", symbol, reference=target)
        for symbol, ids in bindings:
            for identifier in ids:
                if identifier not in operations:
                    reject("missing-operation", symbol, operation_id=identifier)
        for operation in executable.operations:
            if operation.effect.operation not in {
                "set_flag", "clear_flag", "set_quest_status", "record_dialogue_choice", "transfer_item",
            }:
                reject("unsupported-effect", operation.symbol, operation=operation.effect.operation)
            if operation.execution == "host" and operation.host_binding_id not in host_ids:
                reject("missing-host-binding", operation.symbol, binding=operation.host_binding_id or "")
        visited = set()
        def visit(symbol, path):
            if symbol in path:
                reject("recursive-call", symbol, reason="Flow call cycle cannot be exported")
                return
            if symbol in visited:
                return
            for target in call_graph.get(symbol, []):
                visit(target, path | {symbol})
            visited.add(symbol)
        for symbol in call_graph:
            visit(symbol, set())
        mapped = defined | {
            *(route.symbol for flow in executable.flows for step in flow.steps for route in step.routes),
            *(item.symbol for flow in executable.flows for item in flow.returns),
            *(option.symbol for dialogue in executable.dialogues for choice in dialogue.choices for option in choice.options),
            *(branch.symbol for quest in executable.quests for stage in quest.stages for branch in stage.branches),
            *(operation.symbol for operation in executable.operations),
        }
        for symbol in sorted(mapped):
            if symbol not in owners:
                reject("missing-source-owner", reference=symbol)
        return diagnostics

    @staticmethod
    def _diagnostic(code, owner, parameters, *, severity="error") -> ExportDiagnosticV1:
        return ExportDiagnosticV1(
            code=f"export.ink.{code}", severity=severity,
            message_key=f"export.diagnostic.ink-{code}", owner=owner, parameters=parameters,
        )
