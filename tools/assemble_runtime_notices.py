"""Archive reviewed Python notice bytes; never approve binaries or fetch sources."""

import argparse
from hashlib import sha256
import json
from pathlib import Path
import re
import tomllib
from urllib.parse import urlsplit

from packaging.utils import canonicalize_name

SYSTEMS = {"Darwin", "Linux", "Windows"}
MAX_REPORT_BYTES = 16 * 1024 * 1024
MAX_TEXT_BYTES = 1024 * 1024
README = """# Python Runtime Notice Texts

Generated by tools/assemble_runtime_notices.py from pinned native-build reports.
The index binds package/version/platform evidence to verbatim license texts and
exact locked source-archive references, where available.

This is a source-only notice archive, not a complete distribution notice bundle,
verified corresponding source or redistribution approval. Native/interpreter,
installer, frontend/Rust and asset review remain separate gates. No installer
upload is enabled by these files. Missing sources and declarations are explicit
in index.json; package source references do not identify embedded libraries.
"""


def digest(data: bytes) -> str:
    return sha256(data).hexdigest()


def safe_path(value: str) -> bool:
    return isinstance(value, str) and bool(value) and "\\" not in value and ":" not in value and not any(ord(char) < 32 for char in value) and all(
        part not in ("", ".", "..") for part in value.split("/")
    )


def checked_digest(value: str) -> str:
    if not isinstance(value, str) or not re.fullmatch(r"[a-f0-9]{64}", value):
        raise ValueError("notice_digest_invalid")
    return value


def source_reference(package: dict | None) -> dict | None:
    if package is None or not package.get("sdist"):
        return None
    archive = package["sdist"]
    url = urlsplit(archive["url"])
    if url.scheme != "https" or url.hostname != "files.pythonhosted.org" or url.username or url.password or url.query or url.fragment:
        raise ValueError("notice_source_url_not_public")
    if not archive["hash"].startswith("sha256:"):
        raise ValueError("notice_source_digest_invalid")
    return {"url": archive["url"], "sha256": checked_digest(archive["hash"][7:]),
            "status": "locked_reference_only_not_downloaded_or_verified"}


def assemble(lock_path: Path, receipts_path: Path, reports: dict[str, Path], output: Path) -> dict:
    """Validate all evidence before creating one fresh, non-overwriting archive."""
    lock_bytes = lock_path.read_bytes().replace(b"\r\n", b"\n")
    lock = tomllib.loads(lock_bytes.decode("utf-8"))
    locks = {}
    for item in lock["package"]:
        identity = canonicalize_name(item["name"]), item["version"]
        if identity in locks:
            raise ValueError("notice_locked_source_ambiguous")
        locks[identity] = item
    accepted_locks = {digest(lock_bytes), digest(lock_bytes.replace(b"\n", b"\r\n"))}
    receipt_bytes = receipts_path.read_bytes()
    receipts = json.loads(receipt_bytes)
    if receipts.get("schema_version") != 1 or set(receipts["reports"]) != SYSTEMS or set(reports) != SYSTEMS:
        raise ValueError("notice_report_set_invalid")
    for receipt in receipts["reports"].values():
        if set(receipt) != {"run_url", "sha256"}:
            raise ValueError("notice_receipt_fields_invalid")
    texts: dict[str, bytes] = {}
    packages: dict[tuple[str, str], dict] = {}
    evidence = []
    for system in sorted(SYSTEMS):
        path = reports[system]
        if path.stat().st_size > MAX_REPORT_BYTES:
            raise ValueError("notice_report_too_large")
        data = path.read_bytes()
        if digest(data) != checked_digest(receipts["reports"][system]["sha256"]):
            raise ValueError("notice_report_digest_changed")
        report = json.loads(data.decode("utf-8-sig"))
        if report.get("schema_version") != 1 or report.get("scope") != "raw_runtime_notice_evidence_only" or report.get("distribution_approved") is not False:
            raise ValueError("notice_report_scope_invalid")
        if report["runtime"]["system"] != system or report["runtime"]["lock_sha256"] not in accepted_locks:
            raise ValueError("notice_report_platform_or_lock_changed")
        if not report.get("review_gaps"):
            raise ValueError("notice_review_gaps_missing")
        notices = {}
        for notice in report["notice_texts"]:
            original = notice["path"]
            if not safe_path(original) or original in notices:
                raise ValueError("notice_path_invalid")
            content = notice["text"].encode("utf-8")
            if len(content) > MAX_TEXT_BYTES or b"\0" in content:
                raise ValueError("notice_text_invalid")
            key = checked_digest(notice["sha256"])
            if digest(content) != key:
                raise ValueError("notice_text_digest_changed")
            texts[key] = content
            notices[original] = {"original_path": original, "file": f"licenses/{key}.txt", "sha256": key}
        seen = set()
        for distribution in report["distributions"]:
            metadata = distribution["metadata_path"]
            if not safe_path(metadata) or not metadata.endswith(".dist-info/METADATA") or metadata in seen:
                raise ValueError("notice_metadata_path_invalid")
            seen.add(metadata)
            name, version = distribution["name"], distribution["version"]
            if not isinstance(name, str) or not re.fullmatch(r"[A-Za-z0-9](?:[A-Za-z0-9._-]*[A-Za-z0-9])?", name) or not isinstance(version, str) or not version:
                raise ValueError("notice_package_identity_invalid")
            identity = canonicalize_name(name), version
            locked = locks.get(identity)
            item = packages.setdefault(identity, {"name": identity[0], "version": version,
                "source_archive": source_reference(locked), "review_gaps": [], "evidence": []})
            if locked is None:
                item["review_gaps"] = sorted(set(item["review_gaps"]) | {"distribution_not_in_lock_including_vendored_records"})
            elif item["source_archive"] is None:
                item["review_gaps"] = sorted(set(item["review_gaps"]) | {"locked_distribution_has_no_sdist"})
            references = distribution["bundled_notice_paths"]
            prefix = metadata.rsplit("/", 1)[0] + "/"
            if len(references) != len(set(references)) or any(ref not in notices or not ref.startswith(prefix) for ref in references):
                raise ValueError("notice_distribution_reference_invalid")
            if not references:
                item["review_gaps"] = sorted(set(item["review_gaps"]) | {"bundled_notice_text_missing"})
            if not distribution["license_expression"] and not distribution["license_declaration"]:
                item["review_gaps"] = sorted(set(item["review_gaps"]) | {"license_declaration_missing_requires_text_review"})
            item["evidence"].append({"platform": system, "metadata_path": metadata,
                "license_expression": distribution["license_expression"],
                "license_declaration": distribution["license_declaration"],
                "notices": [notices[ref] for ref in sorted(references)]})
        evidence.append({"platform": system, **receipts["reports"][system],
                         "runtime": {key: report["runtime"][key] for key in ("system", "machine", "python", "pyinstaller", "lock_sha256")},
                         "collector_sha256": checked_digest(report["collector_sha256"]),
                         "manifest_sha256": checked_digest(report["manifest_sha256"]),
                         "review_gaps": report["review_gaps"]})
    index = {"schema_version": 1, "generated_by": "tools/assemble_runtime_notices.py",
        "scope": "python_notice_texts_and_locked_references_only", "distribution_approved": False,
        "source_head_commit": receipts["source_head_commit"], "build_merge_commit": receipts["build_merge_commit"],
        "receipts_sha256": digest(receipt_bytes), "lock_lf_sha256": digest(lock_bytes),
        "report_inputs": evidence, "packages": [packages[key] for key in sorted(packages)],
        "license_texts": [{"file": f"licenses/{key}.txt", "sha256": key} for key in sorted(texts)],
        "review_gaps": ["source_references_not_fulfilled_corresponding_source",
                        "native_interpreter_installer_frontend_rust_asset_review",
                        "human_review_and_distribution_approval"]}
    # Paths below derive only from validated digests, never report-provided names.
    output.mkdir()
    (output / "licenses").mkdir()
    for key, content in sorted(texts.items()):
        (output / "licenses" / f"{key}.txt").write_bytes(content)
    (output / "index.json").write_text(json.dumps(index, indent=2, ensure_ascii=True) + "\n", encoding="utf-8", newline="\n")
    (output / "README.md").write_text(README, encoding="utf-8", newline="\n")
    return index


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--lock", required=True, type=Path)
    parser.add_argument("--receipts", required=True, type=Path)
    for system in sorted(SYSTEMS):
        parser.add_argument(f"--{system.lower()}", required=True, type=Path)
    parser.add_argument("--output", required=True, type=Path)
    args = parser.parse_args()
    result = assemble(args.lock, args.receipts, {system: getattr(args, system.lower()) for system in SYSTEMS}, args.output)
    print(json.dumps({"packages": len(result["packages"]), "license_texts": len(result["license_texts"]),
                      "distribution_approved": result["distribution_approved"]}))


if __name__ == "__main__":
    main()
