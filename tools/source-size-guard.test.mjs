import assert from "node:assert/strict";
import test from "node:test";

import {
  HARD_LIMIT,
  WARNING_LIMIT,
  countPhysicalLines,
  evaluateSourceSizes,
  exclusionReason,
  formatDiagnostic,
  normalizeRepositoryPath
} from "./source-size-guard.mjs";

function lines(count) {
  return count === 0 ? "" : `${"line\n".repeat(count - 1)}line`;
}

test("counts physical lines without inventing a line after a terminal newline", () => {
  assert.equal(countPhysicalLines(""), 0);
  assert.equal(countPhysicalLines("one"), 1);
  assert.equal(countPhysicalLines("one\n"), 1);
  assert.equal(countPhysicalLines("one\r\ntwo\r\n"), 2);
});

test("warns above 1000 lines and fails only above 2000 lines", () => {
  const result = evaluateSourceSizes([
    { path: "apps/web/src/exact-warning.ts", content: lines(1_000) },
    { path: "apps/web/src/warning.ts", content: lines(1_001) },
    { path: "services/runtime/exact-hard.py", content: lines(2_000) },
    { path: "services/runtime/hard.py", content: lines(2_001) }
  ]);

  assert.deepEqual(
    result.diagnostics.map(({ path, level, code }) => [path, level, code]),
    [
      ["apps/web/src/warning.ts", "warning", "warning_limit"],
      ["services/runtime/exact-hard.py", "warning", "warning_limit"],
      ["services/runtime/hard.py", "error", "hard_limit"]
    ]
  );
});

test("covers every documented exclusion while retaining executable fixture helpers", () => {
  assert.equal(exclusionReason("docs/example.ts", "code"), "documentation");
  assert.equal(
    exclusionReason("services/runtime/migrations/versions/001.py", "code"),
    "database-migration"
  );
  assert.equal(
    exclusionReason("apps/web/src/localization/catalogs.ts", "code"),
    "localization-catalog"
  );
  assert.equal(exclusionReason("fixtures/project.json", "{}"), "static-data");
  assert.equal(exclusionReason("apps/web/dist/bundle.js", "code"), "output-or-dependency");
  assert.equal(exclusionReason("services/vendor/library.py", "code"), "output-or-dependency");
  assert.equal(exclusionReason("apps/web/src/schema.generated.ts", "code"), "generated-source");
  assert.equal(
    exclusionReason("packages/contracts/src/schema.ts", "// @generated by schema-tool\ncode"),
    "generated-source"
  );
  assert.equal(exclusionReason("apps/web/src/testFixtures/builders.ts", "code"), null);
  assert.equal(exclusionReason("README.md", "text"), "unsupported-extension");
});

test("rejects every oversized file without baseline or inline waiver metadata", () => {
  const result = evaluateSourceSizes([{
    path: "apps/web/src/Oversized.tsx",
    content: lines(2_001),
    baseline: 9_999,
    allowOversize: true
  }]);

  assert.deepEqual(result.diagnostics.map(({ level, code }) => [level, code]), [
    ["error", "hard_limit"]
  ]);
  assert.equal(result.errorCount, 1);
});

test("normalizes repository paths before applying limits", () => {
  assert.equal(normalizeRepositoryPath("./apps\\web\\src\\App.tsx"), "apps/web/src/App.tsx");
  const result = evaluateSourceSizes([{
    path: ".\\services\\runtime\\oversized.py",
    content: lines(2_001)
  }]);

  assert.equal(result.diagnostics[0].path, "services/runtime/oversized.py");
});

test("reports checked, excluded, warning, and error totals independently", () => {
  const result = evaluateSourceSizes([
    { path: "apps/web/src/small.ts", content: "code" },
    { path: "apps/web/src/warning.ts", content: lines(1_001) },
    { path: "services/runtime/hard.py", content: lines(2_001) },
    { path: "docs/example.ts", content: lines(3_000) }
  ]);

  assert.deepEqual(
    {
      checked: result.checkedCount,
      excluded: result.excludedCount,
      warnings: result.warningCount,
      errors: result.errorCount
    },
    { checked: 3, excluded: 1, warnings: 1, errors: 1 }
  );
});

test("sorts diagnostics by repository path and formats stable output", () => {
  const result = evaluateSourceSizes([
    { path: "services/z.py", content: lines(2_001) },
    { path: "apps/a.ts", content: lines(1_001) }
  ]);

  assert.deepEqual(result.diagnostics.map((item) => item.path), ["apps/a.ts", "services/z.py"]);
  assert.equal(
    formatDiagnostic(result.diagnostics[0]),
    "WARNING apps/a.ts:1001:1000 warning_limit"
  );
});
