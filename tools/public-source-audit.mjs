// Read-only source/public comparison; private reports never become publication inputs.
import { execFileSync, spawnSync } from "node:child_process";
import { createHash } from "node:crypto";
import { appendFileSync, existsSync, lstatSync, mkdirSync, readFileSync, realpathSync, renameSync, writeFileSync } from "node:fs";
import { basename, dirname, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";
import { isPublicSourcePath, publicReadme } from "./public-source-export.mjs";

const ROOT = fileURLToPath(new URL("../", import.meta.url));
const sha = bytes => createHash("sha256").update(bytes).digest("hex");
const git = (root, args) => execFileSync("git", ["-C", root, ...args], { encoding: "utf8" });
const paths = root => [...new Set(git(root, ["ls-files", "--cached", "--others", "--exclude-standard", "-z"]).split("\0").filter(Boolean))].sort();

function head(root) {
  const result = spawnSync("git", ["-C", root, "rev-parse", "--verify", "HEAD"], { encoding: "utf8" });
  return result.status === 0 ? result.stdout.trim() : null;
}

function fileInfo(root, path) {
  const location = resolve(root, path);
  if (!existsSync(location)) return null;
  const info = lstatSync(location);
  if (!info.isFile() || info.isSymbolicLink()) throw new Error(`Not a regular file: ${path}`);
  return { sha256: sha(readFileSync(location)), bytes: info.size, mode: info.mode & 0o777 };
}

function exclusionReason(path) {
  if (path.split("/").includes("AGENTS.md")) return "agent-instructions";
  if (path.split("/").includes("narrative_graph_agent_system_master_plan.md")) return "master-plan";
  if (path.startsWith("docs/")) return "documentation-outside-guides";
  return "unsafe-path";
}

export function auditPublicSource({ source = ROOT, target }) {
  const sourceRoot = realpathSync(source), targetRoot = realpathSync(target);
  if (sourceRoot === targetRoot || sourceRoot.startsWith(targetRoot + sep) || targetRoot.startsWith(sourceRoot + sep)) throw new Error("Repositories must be separate");
  const candidates = paths(sourceRoot), targetPaths = paths(targetRoot);
  const allowed = candidates.filter(isPublicSourcePath);
  const expected = new Set(allowed);
  const files = allowed.map(path => {
    const original = fileInfo(sourceRoot, path), published = fileInfo(targetRoot, path);
    const expectedHash = path === "README.md" ? sha(publicReadme()) : original?.sha256 ?? null;
    let status;
    if (!original) status = "missing-source";
    else if (!published) status = "missing-public";
    else if (published.sha256 !== expectedHash || published.mode !== original.mode) status = "unexpected-difference";
    else status = original.sha256 === published.sha256 ? "identical" : "readme-replacement";
    return { path, status, source: original, public: published, expected_public_sha256: expectedHash };
  });
  const extras = targetPaths.filter(path => !expected.has(path)).map(path => ({ path, public: fileInfo(targetRoot, path) }));
  const excluded = candidates.filter(path => !isPublicSourcePath(path)).map(path => ({ path, reason: exclusionReason(path) }));
  const counts = Object.fromEntries(["identical", "readme-replacement", "missing-source", "missing-public", "unexpected-difference"].map(status => [status, files.filter(file => file.status === status).length]));
  return {
    schema_version: 1, captured_at: new Date().toISOString(),
    source_repository: basename(sourceRoot), public_repository: basename(targetRoot),
    source_commit: head(sourceRoot), public_commit: head(targetRoot),
    source_worktree_dirty: Boolean(git(sourceRoot, ["status", "--porcelain"]).trim()),
    public_has_history: Boolean(git(targetRoot, ["rev-list", "--all"]).trim()),
    public_has_remote: Boolean(git(targetRoot, ["remote"]).trim()),
    summary: { selected: files.length, excluded: excluded.length, ...counts, extra_public: extras.length },
    files, excluded, extra_public_files: extras
  };
}

export function renderAuditSummary(report) {
  const changes = report.files.filter(file => file.status !== "identical");
  return `# Public Source Differences

Generated by tools/public-source-audit.mjs; do not edit this snapshot by hand.
Captured: ${report.captured_at}. Source commit: ${report.source_commit ?? "none"}.
Source working tree has uncommitted changes: ${report.source_worktree_dirty}.

## Transfer Inventory

The complete per-file list, SHA256 hashes, byte sizes and modes are in
[public-copy-manifest.json](public-copy-manifest.json). It records the actual
comparison, not an assumption that a previous copy is still current.

- Selected source files: ${report.summary.selected}.
- Byte/mode-identical files: ${report.summary.identical}.
- Intentional README replacement: ${report.summary["readme-replacement"]}.
- Missing public files: ${report.summary["missing-public"]}.
- Missing source files: ${report.summary["missing-source"]}.
- Unexpected content/mode differences: ${report.summary["unexpected-difference"]}.
- Extra nonignored public files: ${report.summary.extra_public}.
- Excluded source paths: ${report.summary.excluded} (full list and reasons in manifest).

## Differences

| File | Status | Reason |
|------|--------|--------|
${changes.map(file => `| \`${file.path}\` | ${file.status} | ${file.status === "readme-replacement" ? "Public introduction/development/license text; private documentation links removed" : "Needs explicit review; audit does not overwrite or delete"} |`).join("\n") || "| None | identical | No source/public differences |"}
${report.extra_public_files.map(file => `| \`${file.path}\` | extra-public | No corresponding allowed source path; review before publication |`).join("\n")}

## Exclusion Policy

Every AGENTS.md and narrative_graph_agent_system_master_plan.md is excluded.
Only docs/guides is copied from docs. Git history/metadata and ignored local
projects, secrets, dependencies and build artifacts are not copied. File hashes
do not prove a complete secret, dependency-license or publication audit.

## Publication State

- Public HEAD: ${report.public_commit ?? "none"}.
- Public Git history exists: ${report.public_has_history}.
- A public Git remote is configured: ${report.public_has_remote}.
- This audit performs no Git commit, remote operation, file synchronization or push.
- Copying all tests does not make documentation-dependent checks CI-ready.

Re-run the audit after every source/public task. Unexpected differences, additions
and removals must be reviewed and recorded, never silently overwritten or waived.
`;
}

/** Explicit recording writes only generated private reports, never the public tree. */
export function recordPublicAudit(report, directory, target) {
  const requested = resolve(directory), targetRoot = realpathSync(target);
  let ancestor = requested;
  while (!existsSync(ancestor)) ancestor = dirname(ancestor);
  const destination = resolve(realpathSync(ancestor), relative(ancestor, requested));
  if (destination === targetRoot || destination.startsWith(targetRoot + sep)) throw new Error("Audit records must stay outside the public repository");
  mkdirSync(directory, { recursive: true });
  const reportRoot = realpathSync(directory);
  if (reportRoot === targetRoot || reportRoot.startsWith(targetRoot + sep)) throw new Error("Audit records must stay outside the public repository");
  const json = JSON.stringify(report, null, 2) + "\n";
  for (const [name, text] of [["public-copy-manifest.json", json], ["public-differences.md", renderAuditSummary(report)]]) {
    const temporary = resolve(reportRoot, `${name}.tmp`);
    writeFileSync(temporary, text, { flag: "wx" });
    renameSync(temporary, resolve(reportRoot, name));
  }
  appendFileSync(resolve(reportRoot, "public-transfer-log.jsonl"), JSON.stringify({
    event: "verified-snapshot", captured_at: report.captured_at,
    source_commit: report.source_commit, source_worktree_dirty: report.source_worktree_dirty,
    public_commit: report.public_commit, summary: report.summary, manifest_sha256: sha(json)
  }) + "\n");
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  if (![1, 3].includes(args.length) || (args.length === 3 && args[1] !== "--record-dir")) throw new Error("Usage: node tools/public-source-audit.mjs TARGET [--record-dir PRIVATE_DIRECTORY]");
  const report = auditPublicSource({ target: args[0] });
  if (args[2]) recordPublicAudit(report, resolve(args[2]), args[0]);
  console.log(JSON.stringify({ source_commit: report.source_commit, public_commit: report.public_commit, ...report.summary }, null, 2));
}
